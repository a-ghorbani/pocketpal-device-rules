#!/usr/bin/env python3
"""Render the tier x model matrix from the v2 rules files into README.md.

    python3 tools/render_matrix.py          # rewrite the README section between the markers
    python3 tools/render_matrix.py --check  # exit 1 if the README section is stale (CI)

The section is generated, never hand-edited: a hand-maintained copy drifts from the JSON.
"""
import json
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
README = ROOT / "README.md"
START, END = "<!-- matrix:start -->", "<!-- matrix:end -->"
TIERS = ["low", "mid", "high", "flagship"]
PLATFORMS = [("android", "🤖"), ("ios", "🍎")]

# (heading, model-id prefixes). Anything unmatched lands in "Other families".
FAMILIES = [
    ("Gemma", ("gemma",)),
    ("Qwen", ("qwen",)),
    ("LFM (Liquid AI)", ("lfm",)),
    ("Bonsai (Prism ML)", ("bonsai", "ternary-bonsai")),
    ("Spark-X", ("spark",)),
]
OTHER = "Other families"


def family(model):
    for name, prefixes in FAMILIES:
        if model.startswith(prefixes):
            return name
    return OTHER


def collect():
    models = {}
    for platform, _ in PLATFORMS:
        doc = json.loads((ROOT / f"rules.{platform}.v2.json").read_text())
        for tier in TIERS:
            for c in doc["tiers"][tier]["candidates"]:
                m = models.setdefault(c["model"], {"name": c["display_name"], "params": 0, "tiers": {},
                                                   "vision": set(), "gate": set()})
                m["params"] = max(m["params"], c.get("params") or 0)
                m["tiers"].setdefault(tier, set()).add(platform)
                if c.get("mmproj"):
                    m["vision"].add(platform)
                if c.get("min_app_version"):
                    m["gate"].add(c["min_app_version"])
    return models


def size(params):
    return f"{params / 1e9:.1f}B" if params else "?"


def name_cell(m):
    s = m["name"]
    if len(m["vision"]) == len(PLATFORMS):
        s += " 👁"
    elif m["vision"]:
        s += " 👁 (" + {"ios": "iOS", "android": "Android"}[next(iter(m["vision"]))] + " only)"
    return s


def gate_cell(m):
    return " / ".join(f"≥ {g}" for g in sorted(m["gate"])) or "any"


def tier_cell(m, tier):
    on = m["tiers"].get(tier, set())
    return " ".join(icon for platform, icon in PLATFORMS if platform in on) or "—"


def render():
    models = collect()
    out = ["_Generated by `tools/render_matrix.py` from the v2 rules files — do not edit by hand._", ""]

    out += ["| Tier | Android | iOS |", "|---|:-:|:-:|"]
    for tier in TIERS:
        counts = [sum(1 for m in models.values() if p in m["tiers"].get(tier, set())) for p, _ in PLATFORMS]
        out.append(f"| {tier} | {counts[0]} | {counts[1]} |")
    out += ["", "🤖 Android · 🍎 iOS · 👁 accepts images (ships a vision projector) · **Needs app**: "
            "`min_app_version`; older apps hide the entry. Size is the language model's parameter count "
            "from `params` (the vision projector is not included; MoE and Gemma \"E\" models count all parameters).", ""]

    order = [f for f, _ in FAMILIES] + [OTHER]
    for fam in order:
        rows = sorted((m for k, m in models.items() if family(k) == fam), key=lambda m: (m["params"], m["name"]))
        if not rows:
            continue
        out += [f"#### {fam}", "", "| Size | Model | Needs app | Low | Mid | High | Flagship |",
                "|--:|---|:-:|:-:|:-:|:-:|:-:|"]
        for m in rows:
            out.append(f"| {size(m['params'])} | {name_cell(m)} | {gate_cell(m)} | "
                       + " | ".join(tier_cell(m, t) for t in TIERS) + " |")
        out.append("")
    return "\n".join(out).rstrip() + "\n"


def splice(text, body):
    i, j = text.find(START), text.find(END)
    if i < 0 or j < i:
        raise SystemExit(f"README.md is missing the {START} / {END} markers")
    return text[:i + len(START)] + "\n" + body + text[j:]


def is_stale():
    text = README.read_text()
    return splice(text, render()) != text


if __name__ == "__main__":
    if sys.argv[1:] == ["--check"]:
        if is_stale():
            sys.exit("README tier matrix is stale: run python3 tools/render_matrix.py")
        print("README tier matrix is up to date")
    else:
        README.write_text(splice(README.read_text(), render()))
        print("README tier matrix written")
